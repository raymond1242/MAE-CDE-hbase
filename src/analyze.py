"""Retrieve the records from HBase, compute the indicators and save the results.

Data sources (--source):
  thrift    direct connection to HBase with happybase (recommended)
  shell     parse a `scan 'emp'` export from the HBase shell (fallback)
  snapshot  re-process results/emp_snapshot.csv, which was already extracted
            from HBase, without connecting to the cluster

Outputs (in --outdir, default results/):
  emp_snapshot.csv                   raw data exactly as read from HBase
  extraction_metadata.json           how, when and from where it was read
  01_employees_by_city.csv           Q1 and Q2: employees and % per city
  02_salary_summary.csv              Q3: average, minimum and maximum salary
  03_employees_by_designation.csv    Q4: employees per designation
  04_salary_by_city.csv              Q5: average salary per city (ranking)
  05_data_quality.csv                every missing/invalid/normalized value
  results.md                         all tables in Markdown for the report

Usage:
    python3 src/analyze.py --source thrift
    python3 src/analyze.py --source shell --scan-file results/raw/scan_emp.txt
    python3 src/analyze.py --source snapshot
"""
import argparse
import csv
import json
import platform
from datetime import datetime, timezone
from pathlib import Path

import hbase_readers
from config import MIN_SALARIES_PER_CITY, MISSING_LABEL, RESULTS_DIR, TABLE_NAME, THRIFT_HOST, THRIFT_PORT
from indicators import compute_all


def fmt(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def write_csv(path, rows, columns):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(columns)
        for row in rows:
            writer.writerow([fmt(row.get(col)) for col in columns])


def markdown_table(rows, columns):
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for row in rows:
        lines.append("| " + " | ".join(fmt(row.get(col)) or "—" for col in columns) + " |")
    return "\n".join(lines)


def read_records(args):
    if args.source == "thrift":
        return hbase_readers.read_via_thrift(args.host, args.port, args.table, args.transport, args.protocol)
    if args.source == "shell":
        if not args.scan_file:
            raise SystemExit("--source shell requires --scan-file (output of: scan 'emp')")
        return hbase_readers.read_via_shell_export(args.scan_file, args.table)
    return hbase_readers.read_snapshot(args.snapshot or Path(args.outdir) / "emp_snapshot.csv")


# (output file, results key, columns, section title in results.md)
TABLES = [
    ("01_employees_by_city.csv", "by_city", ["city", "employees", "percentage"],
     "Q1-Q2. Employees and percentage of the total per city"),
    ("03_employees_by_designation.csv", "by_designation", ["designation", "employees", "percentage"],
     "Q4. Employees per designation"),
    ("04_salary_by_city.csv", "salary_by_city",
     ["rank", "city", "employees", "valid_salaries", "avg_salary", "min_salary", "max_salary", "meets_minimum"],
     f"Q5. Average salary per city (ranked if >= {MIN_SALARIES_PER_CITY} valid salaries)"),
    ("05_data_quality.csv", "issues", ["row_key", "field", "original_value", "problem", "treatment"],
     "Data quality: missing, invalid and normalized values"),
]


def write_outputs(results, outdir, info):
    summary_rows = [{"metric": k, "value": v} for k, v in results["salary_summary"].items()]
    write_csv(outdir / "02_salary_summary.csv", summary_rows, ["metric", "value"])
    for filename, key, columns, _ in TABLES:
        write_csv(outdir / filename, results[key], columns)

    s = results["salary_summary"]
    top = results["top_city"]
    largest = next((r for r in results["by_city"] if r["city"] != MISSING_LABEL), None)
    facts = [
        f"Total employees: {s['total_records']}",
        f"City with the most employees: {largest['city']} ({largest['employees']}, {largest['percentage']:.2f}%)"
        if largest else "City with the most employees: n/a",
        f"Valid salaries: {s['valid_salaries']} (missing: {s['missing_salaries']}, "
        f"invalid: {s['invalid_salaries']}, fixed: {s['fixed_salaries']})",
        f"Average / minimum / maximum salary: {fmt(s['avg_salary'])} / {fmt(s['min_salary'])} / {fmt(s['max_salary'])}",
        f"City with the highest average salary: {top['city']} ({fmt(top['avg_salary'])}, "
        f"{top['valid_salaries']} valid salaries)" if top else
        f"City with the highest average salary: no city has >= {MIN_SALARIES_PER_CITY} valid salaries",
    ]

    sections = [
        "# Results (generated by src/analyze.py)",
        f"- Source: {info['method']}  \n- Table: `{info.get('table', TABLE_NAME)}`  \n"
        f"- Rows read: {info['rows_read']}  \n- Generated: {info.get('extracted_at', 'n/a')}",
        "## Key facts\n\n" + "\n".join(f"- {fact}" for fact in facts),
        "## Q3. Salary summary\n\n" + markdown_table(summary_rows, ["metric", "value"]),
    ]
    for _, key, columns, title in TABLES:
        sections.append(f"## {title}\n\n" + markdown_table(results[key], columns))
    (outdir / "results.md").write_text("\n\n".join(sections) + "\n", encoding="utf-8")
    return facts


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0],
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", choices=["thrift", "shell", "snapshot"], default="thrift")
    parser.add_argument("--table", default=TABLE_NAME)
    parser.add_argument("--host", default=THRIFT_HOST)
    parser.add_argument("--port", type=int, default=THRIFT_PORT)
    parser.add_argument("--transport", choices=["buffered", "framed"], default="buffered")
    parser.add_argument("--protocol", choices=["binary", "compact"], default="binary")
    parser.add_argument("--scan-file", help="HBase shell scan export (for --source shell)")
    parser.add_argument("--snapshot", help="snapshot CSV (for --source snapshot)")
    parser.add_argument("--outdir", default=str(RESULTS_DIR))
    args = parser.parse_args()

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    records, info = read_records(args)
    if not records:
        raise SystemExit("The table returned no rows")
    info["extracted_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    info["python"] = platform.python_version()

    if args.source != "snapshot":
        hbase_readers.write_snapshot(records, outdir / "emp_snapshot.csv")
        (outdir / "extraction_metadata.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")

    results = compute_all(records)
    facts = write_outputs(results, outdir, info)

    print(f"Source: {info['method']} -> {info['rows_read']} rows")
    for fact in facts:
        print(f"  {fact}")
    print(f"Results written to {outdir}/ (see results.md)")


if __name__ == "__main__":
    main()
