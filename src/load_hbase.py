"""Load data/employees.csv into the HBase table 'emp'.

Two methods (the table must already exist: hbase/01_create_table.hbase):

  thrift        Writes directly with happybase through the HBase Thrift
                server (port 9090 on the EMR primary node).
  shell-script  Does not connect to HBase: it generates a file of `put`
                commands to run with `hbase shell -n <file>`. Useful when
                Thrift is not available.

Empty CSV fields are NOT written: in HBase a missing value is a cell that
does not exist, not an empty string.

Loading twice is idempotent: the same row key and column overwrite the
previous value. This script never runs truncate or drop.

Usage:
    python3 src/load_hbase.py --method thrift
    python3 src/load_hbase.py --method shell-script
"""
import argparse
import csv
from pathlib import Path

from config import DATA_DIR, FIELDS, REPO_ROOT, TABLE_NAME, THRIFT_HOST, THRIFT_PORT, column_name


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def cells_for(row):
    """(family:qualifier, value) pairs to write, skipping empty fields."""
    return [(column_name(field), row[field]) for field in FIELDS if row.get(field, "") != ""]


def load_thrift(rows, host, port, table_name, transport, protocol, batch_size=100):
    import happybase  # lazy import: the shell-script method does not need it

    conn = happybase.Connection(host=host, port=port, transport=transport, protocol=protocol)
    try:
        if table_name.encode() not in conn.tables():
            raise SystemExit(
                f"Table '{table_name}' does not exist. Create it first with: "
                f"hbase shell -n hbase/01_create_table.hbase"
            )
        table = conn.table(table_name)
        n_cells = 0
        with table.batch(batch_size=batch_size) as batch:
            for row in rows:
                data = {col.encode(): value.encode("utf-8") for col, value in cells_for(row)}
                batch.put(row["row_key"].encode("utf-8"), data)
                n_cells += len(data)
    finally:
        conn.close()
    print(f"{len(rows)} rows and {n_cells} cells written to '{table_name}' via Thrift ({host}:{port})")


def ruby_quote(value):
    """Single-quoted string that is valid in the HBase shell (JRuby)."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def write_shell_script(rows, out_path, table_name):
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    n_cells = 0
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(f"# Generated by src/load_hbase.py: {len(rows)} rows for table '{table_name}'.\n")
        for row in rows:
            for col, value in cells_for(row):
                f.write(f"put {ruby_quote(table_name)}, {ruby_quote(row['row_key'])}, "
                        f"{ruby_quote(col)}, {ruby_quote(value)}\n")
                n_cells += 1
        f.write(f"count {ruby_quote(table_name)}\n")
        f.write("exit\n")
    print(f"{n_cells} put commands written to {out_path}")
    print(f"Next step: hbase shell -n {out_path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--csv", default=str(DATA_DIR / "employees.csv"), help="input CSV")
    parser.add_argument("--method", choices=["thrift", "shell-script"], default="thrift")
    parser.add_argument("--table", default=TABLE_NAME)
    parser.add_argument("--host", default=THRIFT_HOST, help="Thrift server host")
    parser.add_argument("--port", type=int, default=THRIFT_PORT, help="Thrift server port")
    parser.add_argument("--transport", choices=["buffered", "framed"], default="buffered",
                        help="Thrift transport (must match the server configuration)")
    parser.add_argument("--protocol", choices=["binary", "compact"], default="binary",
                        help="Thrift protocol (must match the server configuration)")
    parser.add_argument("--out", default=str(REPO_ROOT / "hbase" / "generated" / "load_data.hbase"),
                        help="output file for --method shell-script")
    args = parser.parse_args()

    rows = read_csv(args.csv)
    missing = [field for field in ["row_key", *FIELDS] if field not in rows[0]]
    if missing:
        raise SystemExit(f"The CSV is missing the columns {missing}")

    if args.method == "thrift":
        load_thrift(rows, args.host, args.port, args.table, args.transport, args.protocol)
    else:
        write_shell_script(rows, args.out, args.table)


if __name__ == "__main__":
    main()
